-- 2. Procedure: insert daily energy generation and consumption
CREATE OR REPLACE PROCEDURE sp_insert_energy (
    p_record_id IN NUMBER,
    p_date      IN DATE,
    p_source    IN VARCHAR2,
    p_generated IN NUMBER,
    p_consumed  IN NUMBER,
    p_location  IN VARCHAR2
)
IS
BEGIN
    INSERT INTO ENERGY_DATA
    VALUES (p_record_id, p_date, p_source, p_generated, p_consumed, p_location);

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Record inserted successfully.');
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        DBMS_OUTPUT.PUT_LINE('Error: record_id already exists.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
END;
/

