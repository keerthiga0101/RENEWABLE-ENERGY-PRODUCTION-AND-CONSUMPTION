-- 1. Display energy records with date, source, generated, consumed, location
SELECT record_date, energy_source, generated_energy, consumed_energy, location
FROM ENERGY_DATA
ORDER BY record_date, location;

-- 2. Total energy generated by each energy source
SELECT energy_source, SUM(generated_energy) AS total_generated
FROM ENERGY_DATA
GROUP BY energy_source;

-- 3. Daily energy consumption
SELECT record_date, SUM(consumed_energy) AS daily_consumption
FROM ENERGY_DATA
GROUP BY record_date
ORDER BY record_date;

-- 4. Energy surplus or deficit for each record
SELECT record_id, location, generated_energy, consumed_energy,
       (generated_energy - consumed_energy) AS balance,
       CASE
           WHEN generated_energy > consumed_energy THEN 'Surplus'
           WHEN generated_energy < consumed_energy THEN 'Deficit'
           ELSE 'Balanced'
       END AS status
FROM ENERGY_DATA;

-- 5. Total energy generation for each location
SELECT location, SUM(generated_energy) AS total_generation
FROM ENERGY_DATA
GROUP BY location
ORDER BY total_generation DESC;

-- 1. Function: surplus or deficit for a given record
CREATE OR REPLACE FUNCTION fn_energy_balance (p_record_id IN NUMBER)
RETURN NUMBER
IS
    v_balance NUMBER;
BEGIN
    SELECT generated_energy - consumed_energy
    INTO v_balance
    FROM ENERGY_DATA
    WHERE record_id = p_record_id;

    RETURN v_balance;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/

