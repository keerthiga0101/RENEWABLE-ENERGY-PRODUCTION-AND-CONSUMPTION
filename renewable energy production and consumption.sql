-- 3. Procedure: source-wise and location-wise energy report
CREATE OR REPLACE PROCEDURE sp_energy_report
IS
    CURSOR c_report IS
        SELECT energy_source, location,
               SUM(generated_energy) AS total_gen,
               SUM(consumed_energy)  AS total_con,
               SUM(generated_energy) - SUM(consumed_energy) AS net_balance
        FROM ENERGY_DATA
        GROUP BY energy_source, location
        ORDER BY energy_source, location;
BEGIN
    DBMS_OUTPUT.PUT_LINE(RPAD('Source', 10) || RPAD('Location', 15) ||
                         RPAD('Generated', 12) || RPAD('Consumed', 12) || 'Net');
    DBMS_OUTPUT.PUT_LINE(RPAD('-', 55, '-'));

    FOR r IN c_report LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.energy_source, 10) || RPAD(r.location, 15) ||
                             RPAD(r.total_gen, 12) || RPAD(r.total_con, 12) ||
                             r.net_balance);
    END LOOP;
END;
/

